// Regenerates docs/checklist-progress.svg (a treemap: one block per section, one cell per item)
// and the progress line in docs/CHECKLIST.md. Run after every checklist update:
//   node scripts/checklist-progress.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const mdPath = new URL('../docs/CHECKLIST.md', import.meta.url)
const svgPath = new URL('../docs/checklist-progress.svg', import.meta.url)
const md = readFileSync(mdPath, 'utf8')

const sections = []
for (const line of md.split(/\r?\n/)) {
  const h = line.match(/^## (?:\d+\.\s*)?(.+)/)
  if (h) sections.push({ name: h[1].replace(/"/g, ''), items: [] })
  const it = line.match(/^- \[([ x~])\] (.+)/)
  if (it && sections.length) sections.at(-1).items.push({ s: it[1], text: it[2].replace(/[*`]/g, '') })
}
const groups = sections.filter(g => g.items.length)
const all = groups.flatMap(g => g.items)
const done = all.filter(i => i.s === 'x').length
const part = all.filter(i => i.s === '~').length
const pct = Math.round((done / all.length) * 100)

// Squarified treemap (Bruls et al.): lay out values into rect x,y,w,h.
function squarify(items, x, y, w, h) {
  const total = items.reduce((a, b) => a + b.v, 0)
  items = items.map(i => ({ ...i, v: (i.v * w * h) / total }))
  const out = []
  while (items.length) {
    const short = Math.min(w, h)
    const worst = r => {
      const s = r.reduce((a, b) => a + b.v, 0)
      const mx = Math.max(...r.map(b => b.v)), mn = Math.min(...r.map(b => b.v))
      return Math.max((short * short * mx) / (s * s), (s * s) / (short * short * mn))
    }
    let row = [items[0]], i = 1
    while (i < items.length && worst([...row, items[i]]) <= worst(row)) row.push(items[i++])
    items = items.slice(i)
    const thick = row.reduce((a, b) => a + b.v, 0) / short
    let off = 0
    for (const it of row) {
      const len = it.v / thick
      out.push(w >= h ? { ...it, x, y: y + off, w: thick, h: len } : { ...it, x: x + off, y, w: len, h: thick })
      off += len
    }
    if (w >= h) { x += thick; w -= thick } else { y += thick; h -= thick }
  }
  return out
}

const W = 860, H = 380, TOP = 34, LABEL = 18, GAP = 2
const color = { x: '#2ea043', '~': '#d29922', ' ': '#6e7681' }
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const rects = squarify(groups.map(g => ({ g, v: g.items.length })).sort((a, b) => b.v - a.v), 0, TOP, W, H - TOP)

let body = ''
for (const { g, x, y, w, h } of rects) {
  const ih = h - LABEL - GAP * 2, iw = w - GAP * 2
  const n = g.items.length
  const cols = Math.max(1, Math.min(n, Math.round(Math.sqrt((n * iw) / ih))))
  const rows = Math.ceil(n / cols)
  const cw = iw / cols, ch = ih / rows
  // Nested <svg> clips the label to its block.
  body += `<svg x="${x}" y="${y}" width="${w}" height="${h}"><rect width="${w}" height="${h}" fill="#161b22" stroke="#0d1117" stroke-width="2"/>`
  body += `<text x="5" y="13" fill="#e6edf3" font-size="11" font-weight="600">${esc(g.name)}</text>`
  g.items.forEach((it, k) => {
    const cx = GAP + (k % cols) * cw, cy = LABEL + GAP + Math.floor(k / cols) * ch
    body += `<rect x="${cx + 1}" y="${cy + 1}" width="${cw - 2}" height="${ch - 2}" fill="${color[it.s]}"><title>${esc(it.text)}</title></rect>`
  })
  body += '</svg>'
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="-apple-system,Segoe UI,Helvetica,Arial,sans-serif">
<rect width="${W}" height="${H}" fill="#0d1117"/>
<text x="6" y="22" fill="#e6edf3" font-size="15" font-weight="600">Spec checklist: ${pct}% (${done}/${all.length}) · ${part} partly done</text>
<g font-size="11"><rect x="${W - 268}" y="12" width="10" height="10" fill="${color.x}"/><text x="${W - 254}" y="21" fill="#e6edf3">done</text>
<rect x="${W - 210}" y="12" width="10" height="10" fill="${color['~']}"/><text x="${W - 196}" y="21" fill="#e6edf3">partly done</text>
<rect x="${W - 120}" y="12" width="10" height="10" fill="${color[' ']}"/><text x="${W - 106}" y="21" fill="#e6edf3">not started</text></g>
${body}
</svg>
`
writeFileSync(svgPath, svg)

const block = `<!-- progress:start (generated by scripts/checklist-progress.mjs) -->
![Checklist progress: ${done} of ${all.length} done](checklist-progress.svg)

**Progress:** ${done} of ${all.length} done (${pct}%), ${part} partly done, ${all.length - done - part} not started.
<!-- progress:end -->`
const re = /<!-- progress:start[\s\S]*?<!-- progress:end -->/
if (!re.test(md)) throw new Error('CHECKLIST.md is missing the <!-- progress:start --> ... <!-- progress:end --> markers')
writeFileSync(mdPath, md.replace(re, block))
console.log(`${done}/${all.length} done, ${part} partly, ${groups.length} sections`)
